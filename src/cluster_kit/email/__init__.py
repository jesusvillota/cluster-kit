def capture_rich_output(renderable: object) -> str:
    """
    Render a Rich object (Table, Panel, ...) to plain text.

    Useful for embedding the summary tables that scripts already produce into
    the email body.
    """
    buf = StringIO()
    temp_console = Console(file=buf, width=120, no_color=True, force_terminal=False)
    temp_console.print(renderable)
    return buf.getvalue()


