# Convenience wrapper (the function scripts actually call)
# ---------------------------------------------------------------------------


def mail_completion(
    script_path: str,
    args: argparse.Namespace,
    succeeded: bool,
    runtime_seconds: float,
    summary_text: str = "",
    output_files: list[Path | str] | None = None,
    error_message: str = "",
    subject_prefix: str = "[job] |",
    footer_text: str = "cluster-kit notification",
    env_file: Path | None = None,
) -> bool:
    """
    One-call convenience: decide whether to send, format, and dispatch.

    Typical usage at the end of ``main()``::

        mail_completion(
            __file__, args, succeeded=True,
            runtime_seconds=elapsed,
            summary_text=capture_rich_output(summary_table),
        )

    Parameters
    ----------
    script_path : str
        ``__file__`` of the calling script.
    args : argparse.Namespace
        Parsed CLI arguments (must include ``mail_me`` attribute added by
        :func:`add_mail_args`).
    succeeded : bool
        Whether the script completed successfully.
    runtime_seconds : float
        Wall-clock runtime in seconds.
    summary_text : str
        Pre-rendered Rich output to embed in the email body.
    output_files : list[Path] | None
        Files to attach when ``--mail-me output`` is used (PNG, PDF, etc.).
        Ignored when mode is ``log`` or ``off``.
    error_message : str
        If the script failed, the error description to prepend to the summary.
    subject_prefix : str
        Leading token of the subject line.
    footer_text : str
        Footer label shown at the bottom of the email body.
    env_file : Path | None
        Explicit ``.env`` path to load config from (defaults to ``.env`` in cwd).

    Returns
    -------
    bool
        ``True`` if the email was sent, ``False`` otherwise.
    """
    mail_mode = getattr(args, "mail_me", "off")
    if mail_mode == "off":
        teardown_log_capture()
        return False

    status = "success" if succeeded else "failure"
    full_summary = summary_text
    if not succeeded and error_message:
        full_summary = f"ERROR: {error_message}\n\n{summary_text}"

    # ---- Flush log capture to ensure all buffered logs are written ----
    if _log_file_handler is not None:
        _log_file_handler.flush()

    # ---- Collect log preview ----
    log_preview = get_log_preview()

    # ---- Build attachment list ----
    all_attachments: list[Path] = []
    attachment_names: list[str] = []
    skipped: list[str] = []

    # Always attach the log file
    log_path = get_log_file_path()
    if log_path is not None and log_path.exists():
        all_attachments.append(log_path)
        attachment_names.append(log_path.name)

    # In "output" mode, also attach output files
    if mail_mode == "output" and output_files:
        valid, skip_reasons = _filter_attachments(output_files)
        all_attachments.extend(valid)
        attachment_names.extend(p.name for p in valid)
        skipped.extend(skip_reasons)

    # ---- Tear down log capture before sending ----
    teardown_log_capture()

    # ---- Format and send ----
    subject, html_body, plain_body = format_mail_content(
        script_path,
        args,
        status,
        runtime_seconds,
        full_summary,
        log_preview=log_preview,
        attachment_names=attachment_names,
        skipped_attachments=skipped if skipped else None,
        subject_prefix=subject_prefix,
        footer_text=footer_text,
    )
    return send_notification(
        subject, html_body, plain_body, all_attachments, env_file=env_file
    )
