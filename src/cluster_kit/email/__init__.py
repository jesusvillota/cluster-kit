def add_mail_args(parser: argparse.ArgumentParser) -> None:
    """
    Add the ``--mail-me`` flag to *parser*.

    Usage inside a script::

        parser = argparse.ArgumentParser(...)
        add_mail_args(parser)
        args = parser.parse_args()
    """
    group = parser.add_argument_group("email notifications")
    group.add_argument(
        "--mail-me",
        type=str,
        choices=["off", "log", "output"],
        default="log",
        help=(
            "Email mode: off=none, log=email with log attached, "
            "output=log + script outputs attached (default: log)"
        ),
    )


def should_mail(args: argparse.Namespace) -> bool:
    """Return True if an email should be sent given *args*."""
    return getattr(args, "mail_me", "off") != "off"


# ---------------------------------------------------------------------------
# Log capture
# ---------------------------------------------------------------------------

_log_file_path: Path | None = None
_log_file_handler: logging.FileHandler | None = None
_log_capture_logger: logging.Logger | None = None


def setup_log_capture(logger_name: str = "") -> Path:
    """
    Add a ``FileHandler`` to *logger_name* that writes to a temp file.

    Call this **after** logging setup and ``parse_args()``, only when
    ``args.mail_me != "off"``.  The captured log is later attached to the
    email by :func:`mail_completion`.

    Returns the path to the temporary log file.

    .. note::
       Attach to the specific logger your application logs through, not the
       root logger, when that logger is configured with ``propagate = False``
       (otherwise its messages never reach root handlers, and nothing is
       captured).  ``logger_name=""`` targets the root logger.
    """
    global _log_file_path, _log_file_handler, _log_capture_logger

    # If already capturing, return existing path
    if _log_file_path is not None:
        return _log_file_path

    fd, path = tempfile.mkstemp(suffix=".txt", prefix="cluster_kit_")
    os.close(fd)
    _log_file_path = Path(path)

    _log_file_handler = logging.FileHandler(path, mode="w", encoding="utf-8")
    _log_file_handler.setLevel(logging.DEBUG)
    formatter = _StripMarkupFormatter(
        "%(asctime)s | %(levelname)-8s | %(name)s | %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
    )
    _log_file_handler.setFormatter(formatter)
    _log_capture_logger = logging.getLogger(logger_name)
    _log_capture_logger.addHandler(_log_file_handler)

    return _log_file_path


def get_log_file_path() -> Path | None:
    """Return the path to the captured log file, or ``None``."""
    return _log_file_path


def get_log_preview(max_lines: int = 60) -> str:
    """
    Return the first *max_lines / 2* and last *max_lines / 2* lines of the
    captured log.  If the log is shorter than *max_lines*, return it in full.
    """
    if _log_file_path is None or not _log_file_path.exists():
        return "(no log captured)"

    lines = _log_file_path.read_text(encoding="utf-8", errors="replace").splitlines()
    if len(lines) <= max_lines:
        return "\n".join(lines)

    half = max_lines // 2
    head = lines[:half]
    tail = lines[-half:]
    omitted = len(lines) - max_lines
    return "\n".join(head + [f"\n... ({omitted} lines omitted) ...\n"] + tail)


def teardown_log_capture() -> None:
    """Remove the file handler, flushing and closing it (keeps the temp file)."""
    global _log_file_handler, _log_file_path, _log_capture_logger
    if _log_file_handler is not None:
        _log_file_handler.flush()  # Ensure all buffered logs are written to disk
        if _log_capture_logger is not None:
            _log_capture_logger.removeHandler(_log_file_handler)
        _log_file_handler.close()
        _log_file_handler = None
    _log_file_path = None
    _log_capture_logger = None


