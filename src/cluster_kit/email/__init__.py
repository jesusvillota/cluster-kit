def _format_runtime(seconds: float) -> str:
    """Human-readable runtime string."""
    total = int(seconds)
    hours, remainder = divmod(total, 3600)
    minutes, secs = divmod(remainder, 60)
    if hours > 0:
        return f"{hours}h {minutes}m {secs}s"
    if minutes > 0:
        return f"{minutes}m {secs}s"
    return f"{secs}s"


def _filter_attachments(
    paths: list[Path | str],
) -> tuple[list[Path], list[str]]:
    """
    Filter *paths* by existence and size (``MAX_ATTACHMENT_BYTES``).

    Accepts both ``Path`` objects and plain strings (auto-converted).

    Returns ``(valid, skipped)`` where *skipped* contains human-readable
    reasons for each dropped file.
    """
    valid: list[Path] = []
    skipped: list[str] = []
    for p in paths:
        p = Path(p)
        if not p.exists():
            skipped.append(f"{p.name} (file not found)")
            continue
        size = p.stat().st_size
        if size > MAX_ATTACHMENT_BYTES:
            mb = size / 1_000_000
            skipped.append(f"{p.name} ({mb:.1f} MB > 25 MB limit)")
            continue
        valid.append(p)
    return valid, skipped


def format_mail_content(
    script_path: str,
    args: argparse.Namespace,
    status: str,
    runtime_seconds: float,
    summary_text: str = "",
    log_preview: str = "",
    attachment_names: list[str] | None = None,
    skipped_attachments: list[str] | None = None,
    subject_prefix: str = "[job] |",
    footer_text: str = "cluster-kit notification",
) -> tuple[str, str, str]:
    """
    Build email subject, HTML body, and plain-text body.

    Parameters
    ----------
    script_path : str
        ``__file__`` of the calling script.
    args : argparse.Namespace
        Parsed CLI arguments (``mail_me`` is excluded from the email).
    status : str
        ``"success"`` or ``"failure"``.
    runtime_seconds : float
        Wall-clock runtime of the script.
    summary_text : str
        Pre-rendered Rich output (plain text) to include in the email.
    log_preview : str
        Truncated log text for the email body.
    attachment_names : list[str] | None
        Names of files that will be attached (for listing in the body).
    skipped_attachments : list[str] | None
        Descriptions of attachments that were skipped (size limit, etc.).
    subject_prefix : str
        Leading token of the subject line (e.g. ``"[WSB] |"``).
    footer_text : str
        Footer label shown at the bottom of the email body.

    Returns
    -------
    tuple[str, str, str]
        ``(subject, html_body, plain_body)``
    """
    script_name = Path(script_path).stem
    runtime_str = _format_runtime(runtime_seconds)

    status_upper = status.upper()
    is_success = status == "success"
    status_color = "#28a745" if is_success else "#dc3545"
    status_label = "OK" if is_success else "FAIL"

    # ---- subject ----
    subject = f"{subject_prefix} {status_label} | {script_name} | {runtime_str}"

    # ---- arguments table rows ----
    skip_keys = {"mail_me"}
    args_dict = vars(args)
    args_rows_html = ""
    args_lines_plain: list[str] = []
    for key, value in sorted(args_dict.items()):
        if key in skip_keys or value is None:
            continue
        args_rows_html += (
            f"<tr>"
            f"<td style='padding:4px 12px;font-weight:bold;'>{key}</td>"
            f"<td style='padding:4px 12px;'>{value}</td>"
            f"</tr>\n"
        )
        args_lines_plain.append(f"  {key}: {value}")

    # ---- escape helpers ----
    def _esc(text: str) -> str:
        return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

    summary_escaped = _esc(summary_text)
    log_preview_escaped = _esc(log_preview)

    # ---- HTML sections ----
    args_section = ""
    if args_rows_html:
        args_section = (
            "<h3 style='margin:16px 0 8px;'>Arguments</h3>"
            "<table style='border-collapse:collapse;width:100%;margin-bottom:16px;'>"
            f"{args_rows_html}</table>"
        )

    summary_section = ""
    if summary_text:
        summary_section = (
            "<h3 style='margin:16px 0 8px;'>Output Summary</h3>"
            "<pre style='background:#f6f8fa;padding:16px;border-radius:6px;"
            "overflow-x:auto;font-size:13px;line-height:1.5;'>"
            f"{summary_escaped}</pre>"
        )

    log_section = ""
    if log_preview:
        log_section = (
            "<h3 style='margin:16px 0 8px;'>Log Preview</h3>"
            "<pre style='background:#f0f0f0;padding:16px;border-radius:6px;"
            "overflow-x:auto;font-size:12px;line-height:1.4;color:#333;'>"
            f"{log_preview_escaped}</pre>"
            "<p style='font-size:12px;color:#6a737d;'>"
            "Full log attached.</p>"
        )

    attachments_section = ""
    att_lines: list[str] = []
    if attachment_names:
        att_lines.append("<h3 style='margin:16px 0 8px;'>Attachments</h3><ul>")
        for name in attachment_names:
            att_lines.append(f"<li><code>{_esc(name)}</code></li>")
        att_lines.append("</ul>")
    if skipped_attachments:
        att_lines.append(
            "<p style='color:#856404;font-size:13px;'>"
            "<strong>Skipped attachments:</strong></p><ul>"
        )
        for reason in skipped_attachments:
            att_lines.append(f"<li style='color:#856404;'>{_esc(reason)}</li>")
        att_lines.append("</ul>")
    if att_lines:
        attachments_section = "\n".join(att_lines)

    # ---- HTML body ----
    html_body = (
        "<html><body style=\"font-family:'Courier New',monospace;"
        'background:#f6f8fa;padding:20px;">'
        "<div style='max-width:700px;margin:0 auto;background:white;"
        "border-radius:8px;border:1px solid #e1e4e8;overflow:hidden;'>"
        # Header
        f"<div style='background:{status_color};padding:16px 24px;color:white;'>"
        f"<h2 style='margin:0;'>{script_name} &mdash; {status_upper}</h2>"
        "</div>"
        # Body
        "<div style='padding:24px;'>"
        "<table style='border-collapse:collapse;width:100%;margin-bottom:16px;'>"
        "<tr style='border-bottom:1px solid #e1e4e8;'>"
        "<td style='padding:8px 12px;font-weight:bold;'>Script</td>"
        f"<td style='padding:8px 12px;'>{script_path}</td></tr>"
        "<tr style='border-bottom:1px solid #e1e4e8;'>"
        "<td style='padding:8px 12px;font-weight:bold;'>Status</td>"
        f"<td style='padding:8px 12px;color:{status_color};font-weight:bold;'>"
        f"{status_upper}</td></tr>"
        "<tr style='border-bottom:1px solid #e1e4e8;'>"
        "<td style='padding:8px 12px;font-weight:bold;'>Runtime</td>"
        f"<td style='padding:8px 12px;'>{runtime_str}</td></tr>"
        "</table>"
        f"{args_section}"
        f"{summary_section}"
        f"{log_section}"
        f"{attachments_section}"
        "</div>"
        # Footer
        "<div style='padding:12px 24px;background:#f6f8fa;"
        "border-top:1px solid #e1e4e8;font-size:12px;color:#6a737d;'>"
        f"{footer_text}"
        "</div></div></body></html>"
    )

    # ---- plain-text body ----
    args_block = "\n".join(args_lines_plain) if args_lines_plain else "  (none)"
    summary_block = f"\nOutput Summary:\n{summary_text}" if summary_text else ""
    log_block = f"\nLog Preview:\n{log_preview}" if log_preview else ""

    att_block = ""
    if attachment_names:
        att_block += "\nAttachments:\n" + "\n".join(
            f"  - {n}" for n in attachment_names
        )
    if skipped_attachments:
        att_block += "\nSkipped attachments:\n" + "\n".join(
            f"  - {r}" for r in skipped_attachments
        )

    plain_body = (
        f"{script_name} -- {status_upper}\n"
        f"{'=' * 40}\n"
        f"Script:  {script_path}\n"
        f"Status:  {status_upper}\n"
        f"Runtime: {runtime_str}\n\n"
        f"Arguments:\n{args_block}"
        f"{summary_block}"
        f"{log_block}"
        f"{att_block}\n"
    )

    return subject, html_body, plain_body


